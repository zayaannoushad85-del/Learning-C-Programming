// ============================================================================
// Idle / touch (PAT) screens
// ============================================================================

// The JS version applies a symmetric +/-1px bob by offsetting fillRect calls
// in a per-pixel loop. u8g2's drawXBMP takes unsigned coordinates, so a
// literal y=-1 would underflow to 65535 instead of shifting the image up -
// that's a real hazard, not a style choice, so the bob here is deliberately
// asymmetric (0 or +1, never negative) to stay well inside safe unsigned
// arithmetic. Cosmetically this is a slightly different wobble than the
// simulator's; functionally it's the safe choice for hardware.
static uint8_t idleBobOffset(uint32_t tick) {
  float phase = sinf((tick * 2.0f * PI) / 42.0f);
  return (phase > 0.15f) ? 1 : 0;
}

static void drawIdleFace(uint32_t tick) {
  uint8_t bob = idleBobOffset(tick);
  u8g2.setDrawColor(1);
  u8g2.drawXBMP(0, bob, DISPLAY_WIDTH, DISPLAY_HEIGHT, DOG_FINE_XBM);
}

// Erases the extracted neutral mouth/nose region back to solid "on", then
// draws a grin curve on top - high at the corners, dipping at the center.
// Coordinates ported directly from the verified drawSmile() in the
// simulator (cx=64, half-width=24, depth=9).
static void drawSmileOverlay() {
  u8g2.setDrawColor(1);
  u8g2.drawBox(47, 43, 90 - 47, 63 - 43); // erase old mouth: (46,42)-(90,63) exclusive
  u8g2.setDrawColor(0);
  for (int16_t x = 41; x <= 87; x++) {
    float t = (x - 64) / 24.0f;
    float centerY = 50.0f + 9.0f * (1.0f - t * t);
    int16_t yTop = (int16_t)lroundf(centerY - 2.2f);
    int16_t yBot = (int16_t)lroundf(centerY + 2.2f);
    if (yTop < 0) yTop = 0;
    u8g2.drawVLine(x, yTop, (yBot - yTop) + 1);
  }
  u8g2.setDrawColor(1);
}

static void drawPatScreen(uint32_t tick) {
  drawIdleFace(tick);
  drawSmileOverlay();
  // small sparkle blips, ported from the simulator's PAT overlay
  int16_t sparkles[3][2] = {{-34, 6}, {34, 2}, {0, -32}};
  for (uint8_t i = 0; i < 3; i++) {
    uint32_t p = (tick + i * 7) % 20;
    int16_t cx = 64 + sparkles[i][0];
    int16_t cy = 34 + sparkles[i][1] - (int16_t)(p * 0.7f);
    if (cy < -3 || cy > 66) continue; // fully offscreen, skip
    u8g2.drawBox(cx - 2, cy - 2, 4, 4);
  }
}

