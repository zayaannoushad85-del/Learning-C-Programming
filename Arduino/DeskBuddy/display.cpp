void display_init() {
  Wire.begin(DISPLAY_I2C_SDA_PIN, DISPLAY_I2C_SCL_PIN);
  Wire.setClock(DISPLAY_I2C_CLOCK_HZ);
  u8g2.setI2CAddress(DISPLAY_I2C_ADDRESS << 1); // u8g2 wants the 8-bit address
  u8g2.begin();
  u8g2.clearBuffer();
  u8g2.sendBuffer();
}

void display_render(const DisplayData& d) {
  u8g2.clearBuffer();
  u8g2.setDrawColor(1);

  switch (d.screen) {
    case ScreenID::IDLE:     drawIdleFace(d.animTick); break;
    case ScreenID::PAT:      drawPatScreen(d.animTick); break;
    case ScreenID::CLOCK:    drawClockScreen(d); break;
    case ScreenID::POMODORO: drawPomodoroScreen(d); break;
    case ScreenID::WEATHER:  drawWeatherScreen(d); break;
    case ScreenID::SETTINGS: drawSettingsScreen(d); break;
    default:                 drawIdleFace(d.animTick); break; // LISTENING/SPEAKING land here until Phase 2
  }

  u8g2.sendBuffer();
}
